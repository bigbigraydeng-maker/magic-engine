-- 🔴 为什么要这一列（2026-09-24 两位复审同时点名）：
--    改成「所有表单汇总进一张表」之后，上线多了一步**人工动作** —— 有人要照着
--    约定去动目标表格的表头（CTS 这次是在表尾加两列）。加错位置、或者以后有人
--    在表中间插一列，ME 照样按配置把每一格写满：电话写进邮箱列、员工的跟进记录被推走，
--    而 `appended` 正常、回执全绿、日报绿、一条待办都不出。
--    这张表是销售直接看的 —— **错位比不写更糟**。
--
--    模块本来就把整张表读回来了，第一行是白拿的。配上这一列就能开工前对一次表头，
--    对不上就这轮不写 + 出待办，跟这条链路其它地方的 fail-closed 一个纪律。
--
--    留空 = 不检查（老配置、还没定表头的新客户照常跑，行为不变）。

ALTER TABLE public.client_lead_sheet_routes
  ADD COLUMN IF NOT EXISTS header_row text[];

COMMENT ON COLUMN public.client_lead_sheet_routes.header_row IS
  '表头签名：目标表格第一行应该长什么样，逐格比对。长度必须等于 columns。留空 = 不检查。对不上这轮一行不写并出人工待办 —— 防人工排表头排错导致整表错位。';

