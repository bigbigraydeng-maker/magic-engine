describe('expectJson WAF integration (via testWordpressConnection)', () => {
  const realFetch = globalThis.fetch
  let fetchMock: ReturnType<typeof vi.fn>

  beforeEach(() => {
    fetchMock = vi.fn()
    globalThis.fetch = fetchMock as unknown as typeof fetch
  })
  afterEach(() => {
    globalThis.fetch = realFetch
    vi.restoreAllMocks()
  })

  it('surfaces SITEGROUND_ANTIBOT in error message when captcha redirect occurs', async () => {
    fetchMock.mockResolvedValueOnce(makeResponse('<html>captcha</html>', {
      status: 200,
      url:    'https://oztop.com.au/sgcaptcha/?ref=abc',
    }))
    const { testWordpressConnection } = await import('./wordpress-client')
    const result = await testWordpressConnection({
      siteUrl:     'https://oztop.com.au',
      username:    'me',
      appPassword: 'xxxx xxxx xxxx',
    })
    expect(result.ok).toBe(false)
    expect(result.error).toMatch(/SiteGround anti-bot|SITEGROUND/i)
  })

  it('surfaces WORDFENCE_BLOCK on 403 + Wordfence body', async () => {
    fetchMock.mockResolvedValueOnce(makeResponse('Generated by Wordfence', { status: 403 }))
    const { testWordpressConnection } = await import('./wordpress-client')
    const result = await testWordpressConnection({
      siteUrl:     'https://oztop.com.au',
      username:    'me',
      appPassword: 'xxxx xxxx xxxx',
    })
    expect(result.ok).toBe(false)
    expect(result.error).toMatch(/Wordfence/i)
  })
})

describe('wpFetch retry behaviour (via testWordpressConnection)', () => {
  const realFetch = globalThis.fetch
  let fetchMock: ReturnType<typeof vi.fn>

  beforeEach(() => {
    fetchMock = vi.fn()
    globalThis.fetch = fetchMock as unknown as typeof fetch
  })
  afterEach(() => {
    globalThis.fetch = realFetch
    vi.restoreAllMocks()
  })

  it('retries once on 502 then succeeds', async () => {
    fetchMock
      .mockResolvedValueOnce(makeResponse('<html>Bad Gateway</html>', { status: 502 }))
      .mockResolvedValueOnce(makeResponse(
        JSON.stringify({ name: 'oztop-bot', roles: ['author'] }),
        { status: 200 },
      ))
    const { testWordpressConnection } = await import('./wordpress-client')
    const result = await testWordpressConnection({
      siteUrl:     'https://oztop.com.au',
      username:    'me',
      appPassword: 'xxxx xxxx xxxx',
    })
    expect(result.ok).toBe(true)
    expect(fetchMock).toHaveBeenCalledTimes(2)
  })

  it('does NOT retry on 401 (auth error)', async () => {
    fetchMock.mockResolvedValue(makeResponse(
      JSON.stringify({ code: 'rest_unauthorized', message: 'Sorry, you are not allowed' }),
      { status: 401 },
    ))
    const { testWordpressConnection } = await import('./wordpress-client')
    const result = await testWordpressConnection({
      siteUrl:     'https://oztop.com.au',
      username:    'me',
      appPassword: 'xxxx xxxx xxxx',
    })
    expect(result.ok).toBe(false)
    expect(fetchMock).toHaveBeenCalledTimes(1)
  })

  it('does NOT retry on a captcha redirect (status 200 but WAF detected)', async () => {
    fetchMock.mockResolvedValue(makeResponse('<html>captcha</html>', {
      status: 200,
      url:    'https://oztop.com.au/sgcaptcha/?ref=abc',
    }))
    const { testWordpressConnection } = await import('./wordpress-client')
    const result = await testWordpressConnection({
      siteUrl:     'https://oztop.com.au',
      username:    'me',
      appPassword: 'xxxx xxxx xxxx',
    })
    expect(result.ok).toBe(false)
    expect(fetchMock).toHaveBeenCalledTimes(1)
  })

  it('gives up after 2 tries on persistent 5xx', async () => {
    fetchMock.mockResolvedValue(makeResponse('<html>Bad Gateway</html>', { status: 502 }))
    const { testWordpressConnection } = await import('./wordpress-client')
    const result = await testWordpressConnection({
      siteUrl:     'https://oztop.com.au',
      username:    'me',
      appPassword: 'xxxx xxxx xxxx',
    })
    expect(result.ok).toBe(false)
    expect(fetchMock).toHaveBeenCalledTimes(2)
  })
})
