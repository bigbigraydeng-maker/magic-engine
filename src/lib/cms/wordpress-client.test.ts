describe('WordpressFetchError', () => {
  it('extends Error so existing try/catch in callers still works', () => {
    const err = new WordpressFetchError('boom', 'TIMEOUT')
    expect(err).toBeInstanceOf(Error)
    expect(err.message).toBe('boom')
    expect(err.code).toBe('TIMEOUT')
    expect(err.name).toBe('WordpressFetchError')
  })

  it('preserves httpStatus + evidence', () => {
    const err = new WordpressFetchError('block', 'WORDFENCE_BLOCK', 403, 'cookie present')
    expect(err.httpStatus).toBe(403)
    expect(err.evidence).toBe('cookie present')
  })
})

