/**
 * 包拯的提示词——代码里只有这一处，副本在 docs/agents/prompt-library/baozheng-review.md。
 *
 * 复核提示词故意**不**给原 AI 的结论（规则书 BZ-17），也不写任何客户名、行业词：
 * 阶段说明全部来自这个客户自己的阶段表（标签 + 七个大类的说明）。
 */

import type { StageCategory } from './config'

/** 每个大类给复核模型的说明（平台通用，不含行业词）。 */
export const CATEGORY_GUIDE: Readonly<Record<StageCategory, string>> = {
  untouched: 'no real two-way contact with a human on our side yet (form fills and automatic replies do not count)',
  engaged: 'a human on our side has been in real contact and the conversation is ongoing',
  deep: 'we have sent a price, a quote, a proposal or a concrete offer, or a viewing / meeting was arranged',
  won: 'the customer has paid, booked, been served or completed the purchase',
  no_reply: 'we reached out and the customer never answered',
  declined: 'the customer said not now, or said no',
  not_lead: 'not a prospective customer at all: a sales pitch, spam, a mass mailing, a test account',
}

export interface ReviewStageOption {
  key: string
  label: string
  category: StageCategory
}

export const REVIEW_SYSTEM_PROMPT = `You review a sales conversation and decide which pipeline stage the customer was at
AT THE END of the conversation shown. You are an independent second opinion: judge only from the text shown.

Rules:
- Pick exactly one stage key from the list, or "unclear" when the conversation does not show enough.
- Messages generated by a form or by an automatic reply are not the customer speaking and not a human on our side.
- Do not guess payments: a promise to pay is not a payment.
- "reason": one short sentence in Simplified Chinese, at most 60 characters. Do NOT quote the conversation,
  do NOT include any name, email, phone number or price.
- Answer with JSON only: {"stage": "<key or unclear>", "reason": "<sentence>"}`

export function buildReviewUserMessage(options: readonly ReviewStageOption[], transcript: string): string {
  const stageLines = options
    .map((o) => `- ${o.key} (${o.label}): ${CATEGORY_GUIDE[o.category]}`)
    .join('\n')
  return `Stages:\n${stageLines}\n- unclear: the conversation does not show enough\n\nConversation:\n${transcript}`
}
